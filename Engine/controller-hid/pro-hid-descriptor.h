static const unsigned char *nok_pro_descriptor(uint32_t vendor, uint32_t product, bool usb,
    const unsigned char *original, size_t length, size_t *result_length)
{
    *result_length = length;
    if (vendor != 0x057e || product != 0x2009 || !usb || length != sizeof(nok_pro_original) ||
        memcmp(original,nok_pro_original,length)) return original;
    *result_length = sizeof(nok_pro_full_state);
    return nok_pro_full_state;
}
