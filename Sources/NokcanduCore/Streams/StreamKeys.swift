import Foundation

/// Mac virtual key codes (kVK_*) to the Windows virtual-key codes GameStream hosts expect.
public enum StreamKeys {
    public static func windowsKey(_ mac: Int) -> Int? { table[mac] }

    static let table: [Int: Int] = [
        // Letters
        0x00: 0x41, 0x0B: 0x42, 0x08: 0x43, 0x02: 0x44, 0x0E: 0x45, 0x03: 0x46, 0x05: 0x47, 0x04: 0x48, 0x22: 0x49,
        0x26: 0x4A, 0x28: 0x4B, 0x25: 0x4C, 0x2E: 0x4D, 0x2D: 0x4E, 0x1F: 0x4F, 0x23: 0x50, 0x0C: 0x51, 0x0F: 0x52,
        0x01: 0x53, 0x11: 0x54, 0x20: 0x55, 0x09: 0x56, 0x0D: 0x57, 0x07: 0x58, 0x10: 0x59, 0x06: 0x5A,
        // Number row
        0x1D: 0x30, 0x12: 0x31, 0x13: 0x32, 0x14: 0x33, 0x15: 0x34, 0x17: 0x35, 0x16: 0x36, 0x1A: 0x37, 0x1C: 0x38, 0x19: 0x39,
        // Punctuation
        0x1B: 0xBD,   // - _
        0x18: 0xBB,   // = +
        0x21: 0xDB,   // [
        0x1E: 0xDD,   // ]
        0x2A: 0xDC,   // \
        0x29: 0xBA,   // ;
        0x27: 0xDE,   // '
        0x32: 0xC0,   // `
        0x2B: 0xBC,   // ,
        0x2F: 0xBE,   // .
        0x2C: 0xBF,   // /
        0x0A: 0xE2,   // § / the ISO key next to left shift
        // Editing and navigation
        0x24: 0x0D,   // Return
        0x4C: 0x0D,   // keypad Enter
        0x30: 0x09,   // Tab
        0x31: 0x20,   // Space
        0x33: 0x08,   // Delete (backspace)
        0x75: 0x2E,   // Forward delete
        0x35: 0x1B,   // Escape
        0x72: 0x2D,   // Help / Insert
        0x73: 0x24,   // Home
        0x77: 0x23,   // End
        0x74: 0x21,   // Page up
        0x79: 0x22,   // Page down
        0x7B: 0x25, 0x7C: 0x27, 0x7D: 0x28, 0x7E: 0x26,   // arrows: left, right, down, up
        // Modifiers
        0x38: 0xA0, 0x3C: 0xA1,   // shift left, right
        0x3B: 0xA2, 0x3E: 0xA3,   // control left, right
        0x3A: 0xA4, 0x3D: 0xA5,   // option (alt) left, right
        0x37: 0x5B, 0x36: 0x5C,   // command (Windows key) left, right
        0x39: 0x14,               // Caps Lock
        0x3F: 0xFF,               // fn: nothing on Windows (filtered out below)
        // Function keys
        0x7A: 0x70, 0x78: 0x71, 0x63: 0x72, 0x76: 0x73, 0x60: 0x74, 0x61: 0x75, 0x62: 0x76, 0x64: 0x77, 0x65: 0x78,
        0x6D: 0x79, 0x67: 0x7A, 0x6F: 0x7B, 0x69: 0x7C, 0x6B: 0x7D, 0x71: 0x7E, 0x6A: 0x7F, 0x40: 0x80, 0x4F: 0x81,
        0x50: 0x82, 0x5A: 0x83,
        // Keypad
        0x52: 0x60, 0x53: 0x61, 0x54: 0x62, 0x55: 0x63, 0x56: 0x64, 0x57: 0x65, 0x58: 0x66, 0x59: 0x67, 0x5B: 0x68, 0x5C: 0x69,
        0x41: 0x6E,   // keypad .
        0x43: 0x6A,   // keypad *
        0x45: 0x6B,   // keypad +
        0x4E: 0x6D,   // keypad -
        0x4B: 0x6F,   // keypad /
        0x47: 0x90,   // keypad Clear → Num Lock
        0x51: 0xBB,   // keypad =
        // Media
        0x48: 0xAF, 0x49: 0xAE, 0x4A: 0xAD,   // volume up, down, mute
        // JIS
        0x5D: 0xDC,   // ¥
        0x5E: 0xE2,   // _ (JIS underscore)
        0x5F: 0xBC,   // keypad , (JIS)
        0x66: 0x1D,   // 英数 → non-convert
        0x68: 0x1C,   // かな → convert
    ]

    /// Windows modifier keys for the left/right modifier key codes.
    public static let modifierKeys: Set<Int> = [0xA0, 0xA1, 0xA2, 0xA3, 0xA4, 0xA5, 0x5B, 0x5C]
}
