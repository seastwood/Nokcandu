import Foundation

/// A hosted game's settings belong to its small app, never to the EA/Ubisoft client.
public enum HostedSettings {
    public struct Settings: Codable, Hashable {
        public var graphics: GraphicsPreset? = nil
        public var arguments = ""
        public var borderless: Bool? = nil
        public var environment: [String: String] = [:]
        public var launcherSHA: String? = nil
        public init() {}
    }
    static func url(_ contents: URL) -> URL { contents.appendingPathComponent("SharedSupport/nokcandu/hosted-settings.json") }
    public static func load(_ game: InstalledGame) -> Settings {
        if let data = try? Data(contentsOf: url(game.contents)), let saved = try? JSONDecoder().decode(Settings.self, from: data) { return saved }
        var defaults = Settings()
        if let link = game.hosted, let host = host(link), let exe = link.exe,
           let file = BattleNet.unixPath(exe, prefix: host.prefix), let info = PEFile.inspectWithLoadedDLLs(file) { defaults.graphics = GraphicsPreset.suggest(for: info) }
        return defaults
    }
    static func host(_ link: HostedGameLink) -> InstalledGame? { GameLibrary.inspect(URL(fileURLWithPath: link.hostApp)) }
    public static func graphics(_ game: InstalledGame) -> GraphicsPreset {
        load(game).graphics ?? game.hosted.flatMap(host)?.custom?.graphics ?? .classic3D
    }
    static func script(_ link: HostedGameLink, settings: Settings) -> String {
        let q = CustomGames.shellQuote, host = host(link)
        let mode = settings.graphics ?? host?.custom?.graphics ?? .classic3D
        let program = link.exe.flatMap { exe in host.flatMap { BattleNet.unixPath(exe, prefix: $0.prefix) } }
        // Use matching shader helpers shipped beside the game. A renderer must not mask them with
        // Wine replacements (BFBC2's compiler_42 is one example). Never download arbitrary DLLs.
        var overrides = CompatibilityFixes.overrides(mode.mergedDLLOverrides(settings.environment["WINEDLLOVERRIDES"] ?? ""))
        if let program, let info = PEFile.inspect(program),
           let files = try? FileManager.default.contentsOfDirectory(at: program.deletingLastPathComponent(), includingPropertiesForKeys: nil) {
            for file in files where file.lastPathComponent.lowercased().range(of: #"^(d3dx9_[0-9]+|d3dcompiler_[0-9]+)\.dll$"#, options: .regularExpression) != nil {
                let dll = file.deletingPathExtension().lastPathComponent.lowercased()
                if overrides[dll] == nil, PEFile.inspect(file)?.is64Bit == info.is64Bit { overrides[dll] = "n,b" }
            }
        }
        let extraRules = overrides.sorted { $0.key < $1.key }.map { "\($0.key)=\($0.value)" }.joined(separator: ";")
        let extra = settings.environment.filter { $0.key != "WINEDLLOVERRIDES" && CustomGames.isValidEnvName($0.key) }
            .sorted { $0.key < $1.key }.map { "export \($0.key)=\(q($0.value))" }.joined(separator: "\n")
        let command: String
        if link.launcher == .ea, let exe = link.exe {
            command = settings.borderless == true ? #""$SUPPORT/wine/bin/wine" "$BORDERLESS_LAUNCHER""# : #""$SUPPORT/wine/bin/wine" "# + q(exe)
        } else {
            command = #""$SUPPORT/wine/bin/wine" "$LAUNCHER_EXE""# + (link.launcher == .ubisoft ? " " + q("uplay://launch/\(link.id)/0") : "")
        }
        let args = CustomGames.splitArguments(settings.arguments).map(q).joined(separator: " ")
        let script = """
        #!/bin/bash
        # Generated by Nokcandu: per-game settings, shared Windows environment.
        set -euo pipefail
        GAME_CONTENTS="$(cd "$(dirname "$0")/.." && pwd)"
        GAME_STATE="$GAME_CONTENTS/SharedSupport/nokcandu"
        GAME_LOGS="$GAME_CONTENTS/SharedSupport/Logs"
        HOST=\(q(link.hostApp))
        HC="$HOST/Contents"
        CONTENTS="$HC"
        SUPPORT="$HC/SharedSupport"
        LAUNCHER_EXE=\(q(link.launcher.defaultExe))
        [ -x "$SUPPORT/wine/bin/wine" ] || { echo 'The launcher app is missing. Open its page in Nokcandu to repair it.' >&2; exit 1; }
        \(PCLaunchers.hostRunningCheck(link))
        export WINEPREFIX="$SUPPORT/prefix"
        \(WineEnvironment.exportLine("HC"))
        export WINEDEBUG=-all WINEMSYNC=1
        export PATH="$SUPPORT/wine/bin:/usr/bin:/bin:/usr/sbin:/sbin"
        \(HelperPatch.block)
        if [ "${1:-}" = --check ]; then
         \(program.map { "[ -f " + q($0.path) + " ] || { echo 'The selected game program is missing.'; exit 1; }" } ?? ":")
         echo 'Launcher check passed: game and engine are ready.'; exit 0
        fi
        mkdir -p "$GAME_LOGS"
        LOCK="$GAME_LOGS/game.lock"
        if ! mkdir "$LOCK" 2>/dev/null; then
         PREVIOUS_PID=$(cat "$LOCK/pid" 2>/dev/null || true)
         if [[ "$PREVIOUS_PID" =~ ^[0-9]+$ ]] && kill -0 "$PREVIOUS_PID" 2>/dev/null; then exit 0; fi
         rm -f "$LOCK/pid"; rmdir "$LOCK" 2>/dev/null || exit 0; mkdir "$LOCK"
        fi
        echo $$ > "$LOCK/pid"
        trap 'rm -f "$LOCK/pid"; rmdir "$LOCK" 2>/dev/null || true' EXIT
        exec > >(\(CustomGames.logFilter) >"$GAME_LOGS/launch.log") 2>&1
        if ! up; then
         /usr/bin/open -g "$HOST"
         for _ in $(seq 1 90); do sleep 2; up && break; done
         up || { echo 'The launcher did not open. Restart it from Nokcandu and try again.'; exit 1; }
         sleep 20
        fi
        # The client retains its own renderer. Only this game's process gets these settings.
        \(mode.launcherExports.joined(separator: "\n"))
        export DXVK_LOG_PATH="$GAME_LOGS" DXMT_LOG_PATH="$GAME_LOGS"
        \(extraRules.isEmpty ? "" : "export WINEDLLOVERRIDES=" + q(extraRules))
        \(extra)
        \(link.launcher == .ea ? EACompatibility.block(watch: false) : "")
        \(settings.borderless == true && link.exe != nil ? "export NOKCANDU_BORDERLESS_TARGET=" + q(link.exe!) + "\nexport NOKCANDU_BORDERLESS_DLL=" + q(borderlessPath(link, ext: "dll")) + "\nBORDERLESS_LAUNCHER=" + q(borderlessPath(link, ext: "exe")) : "")
        if [ -f "$GAME_STATE/perf.env" ]; then . "$GAME_STATE/perf.env"; fi
        \(program.map { "cd " + q($0.deletingLastPathComponent().path) } ?? ":")
        STATUS=0
        \(command)\(args.isEmpty ? "" : " " + args) || STATUS=$?
        echo "nokcandu: game exited with status $STATUS after ${SECONDS}s"
        exit "$STATUS"

        """
        return HelperPatch.scopeWineLibrary(script)
    }
    public static func save(_ settings: Settings, for game: InstalledGame) throws {
        let launcher = game.launcherURL ?? game.contents.appendingPathComponent("MacOS/\(CustomGames.launcherName)")
        guard let link = game.hosted else { throw NokError("Choose an EA or Ubisoft game added to Nokcandu.") }
        if case .launcherRunning = GameLauncher.runState(of: game) { throw NokError("Quit this game before changing its launch settings.") }
        var value = settings
        let current = try String(contentsOf: launcher, encoding: .utf8), old = load(game)
        guard current == PCLaunchers.legacyLauncherScript(link) || current == PCLaunchers.launcherScript(link, legacyProcessDetection: true) ||
                old.launcherSHA == Hashing.sha256(data: Data(current.utf8)) else {
            throw NokError("This game's launcher was edited outside Nokcandu, so it was kept. Restore the generated launcher before changing settings.")
        }
        if value.borderless == true { try ensureBorderless(link) }
        let script = script(link, settings: value)
        value.launcherSHA = Hashing.sha256(data: Data(script.utf8))
        let journal = ChangeJournal(scope: game.journalScope)
        try journal.write(Data(script.utf8), to: launcher, reason: "Hosted game launch settings")
        try FileManager.default.setAttributes([.posixPermissions: 0o755], ofItemAtPath: launcher.path)
        try journal.write(try JSONEncoder().encode(value), to: url(game.contents), reason: "Hosted game settings")
    }
    static func borderlessPath(_ link: HostedGameLink, ext: String) -> String {
        let arch = link.exe.flatMap { exe in host(link).flatMap { BattleNet.unixPath(exe, prefix: $0.prefix) } }.flatMap(PEFile.inspect)?.is64Bit == true ? "x86_64" : "x86"
        return #"C:\nokcandu\borderless\"# + arch + #"\"# + (ext == "exe" ? "launcher.exe" : "window.dll")
    }
    static func ensureBorderless(_ link: HostedGameLink) throws {
        guard link.launcher == .ea, let host = host(link), let exe = link.exe,
              let program = BattleNet.unixPath(exe, prefix: host.prefix), let info = PEFile.inspect(program) else {
            throw NokError("Fullscreen (Borderless) needs the selected EA game's Windows program.")
        }
        let arch = info.is64Bit ? "x86_64" : "x86"
        let folder = host.prefix.appendingPathComponent("drive_c/nokcandu/borderless/" + arch)
        let stamp = folder.appendingPathComponent("owned-helpers.json")
        var known = ((try? Data(contentsOf: stamp)).flatMap { try? JSONDecoder().decode([String: String].self, from: $0) }) ?? [:]
        for (name, ext) in [("launcher", "exe"), ("window", "dll")] {
            guard let source = NokPaths.bundledResource("borderless-\(arch).\(ext)") else { throw NokError("Nokcandu's borderless helper is missing. Update Nokcandu first.") }
            let target = folder.appendingPathComponent(name + "." + ext), want = try Hashing.sha256(file: source)
            let current = try? Hashing.sha256(file: target)
            guard current == nil || current == want || current == known[target.lastPathComponent] else { throw NokError("The borderless helper was edited outside Nokcandu; it was kept unchanged.") }
            try NokPaths.ensure(folder)
            if current != want { try Data(contentsOf: source).write(to: target, options: .atomic) }
            known[target.lastPathComponent] = want
        }
        try JSONEncoder().encode(known).write(to: stamp, options: .atomic)
    }
    static func initialize(_ link: HostedGameLink, contents: URL, host: InstalledGame) throws {
        var settings = Settings()
        let info = link.exe.flatMap { BattleNet.unixPath($0, prefix: host.prefix) }.flatMap(PEFile.inspectWithLoadedDLLs)
        settings.graphics = GraphicsPreset.suggest(for: info)
        let script = script(link, settings: settings)
        settings.launcherSHA = Hashing.sha256(data: Data(script.utf8))
        try JSONEncoder().encode(settings).write(to: url(contents), options: .atomic)
        try Data(script.utf8).write(to: contents.appendingPathComponent("MacOS/\(CustomGames.launcherName)"), options: .atomic)
    }
}
