import XCTest
@testable import NokcanduCore

final class BattleNetTests: XCTestCase {
    func testParsesBlizzardGamesAndPaths() throws {
        let fm = FileManager.default
        let app = fm.temporaryDirectory.appendingPathComponent("bnet-\(UUID().uuidString.prefix(4))/Battle.net.app")
        let prefix = app.appendingPathComponent("Contents/SharedSupport/prefix")
        try fm.createDirectory(at: prefix.appendingPathComponent("dosdevices"), withIntermediateDirectories: true)
        defer { try? fm.removeItem(at: app.deletingLastPathComponent()) }
        let drive = app.deletingLastPathComponent().appendingPathComponent("Drive")
        try NokPaths.ensure(drive.appendingPathComponent("Diablo II Resurrected"))
        try fm.createSymbolicLink(atPath: prefix.appendingPathComponent("dosdevices/d:").path, withDestinationPath: drive.path)
        let reg = #"""
        WINE REGISTRY Version 2

        [Software\\Wow6432Node\\Microsoft\\Windows\\CurrentVersion\\Uninstall\\Battle.net] 1
        "DisplayName"="Battle.net"
        "UninstallString"="\"C:\\ProgramData\\Battle.net\\Agent\\Blizzard Uninstaller.exe\" --lang=enUS --uid=battle.net --displayname=\"Battle.net\""

        [Software\\Wow6432Node\\Microsoft\\Windows\\CurrentVersion\\Uninstall\\Diablo II Resurrected] 1
        "DisplayIcon"="D:\\Diablo II Resurrected\\D2R.exe"
        "DisplayName"="Diablo II Resurrected"
        "InstallLocation"="D:\\Diablo II Resurrected"
        "UninstallString"="\"C:\\ProgramData\\Battle.net\\Agent\\Blizzard Uninstaller.exe\" --lang=enUS --uid=osi --displayname=\"Diablo II Resurrected\""

        """#
        try Data(reg.utf8).write(to: prefix.appendingPathComponent("system.reg"))
        let host = InstalledGame(appURL: app, name: "Battle.net")
        let games = BattleNet.installedGames(host: host)
        XCTAssertEqual(games.map(\.uid), ["osi"])
        XCTAssertEqual(games.first?.code, "OSI")
        XCTAssertEqual(games.first?.exe, #"D:\Diablo II Resurrected\D2R.exe"#)
        XCTAssertEqual(BattleNet.unixPath(games[0].exe!, prefix: prefix)?.path, drive.appendingPathComponent("Diablo II Resurrected/D2R.exe").path)
        XCTAssertEqual(BattleNet.code(for: "s1"), "S1")

        let script = BattleNet.launcherScript(BattleNetLink(hostApp: app.path, uid: "osi", code: "OSI", name: "Diablo II: Resurrected"))
        let f = app.deletingLastPathComponent().appendingPathComponent("l.sh"); try Data(script.utf8).write(to: f)
        let r = try Shell.run("/bin/bash", ["-n", f.path]); XCTAssertTrue(r.ok, r.combined)
        XCTAssertTrue(script.contains(#"--exec="launch $CODE""#))
    }

    /// Launchers generated by any earlier template are brought up to date; edited ones are left alone.
    func testEarlierGeneratedLaunchersAreUpgradedAndEditedOnesKept() throws {
        let fm = FileManager.default
        let root = fm.temporaryDirectory.appendingPathComponent("bnet-up-\(UUID().uuidString.prefix(6))")
        defer { try? fm.removeItem(at: root) }
        let link = BattleNetLink(hostApp: root.appendingPathComponent("Battle.net.app").path, uid: "s1", code: "S1", name: "StarCraft")
        let current = BattleNet.launcherScript(link)
        // The template as of 0.10: engine exports without Wine 11 variables, no browser block, keep-open.
        let old = current.replacingOccurrences(of: WineEnvironment.exportLine("HC"), with: WineEnvironment.mediaLine("HC"))
            .replacingOccurrences(of: BrowserRenderer.launcherBlock(exes: BrowserRenderer.battleNetExes) + "\n", with: "")
            .replacingOccurrences(of: #"[ ! -f "$STATE/close-with-game" ]"#, with: #"[ -f "$STATE/keep-open" ]"#)
            .replacingOccurrences(of: #"[ -f "$STATE/close-with-game" ]"#, with: #"[ ! -f "$STATE/keep-open" ]"#)
        XCTAssertNotEqual(old, current)
        XCTAssertTrue(BattleNet.earlierLauncherScripts(link).contains(old))
        func game(_ name: String, script: String) throws -> InstalledGame {
            let app = root.appendingPathComponent("\(name).app")
            try NokPaths.ensure(app.appendingPathComponent("Contents/MacOS"))
            try script.write(to: app.appendingPathComponent("Contents/MacOS/\(CustomGames.launcherName)"), atomically: true, encoding: .utf8)
            var g = InstalledGame(appURL: app, name: name); g.battleNet = link
            return g
        }
        let stale = try game("Stale", script: old)
        let edited = try game("Edited", script: old + "echo mine\n")
        BattleNet.refreshLaunchers([stale, edited])
        XCTAssertEqual(try String(contentsOf: stale.appURL.appendingPathComponent("Contents/MacOS/\(CustomGames.launcherName)"), encoding: .utf8), current)
        XCTAssertEqual(try String(contentsOf: edited.appURL.appendingPathComponent("Contents/MacOS/\(CustomGames.launcherName)"), encoding: .utf8), old + "echo mine\n")
    }
}
